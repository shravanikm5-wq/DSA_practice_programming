package Arrays;

public class student {
	String name;
	int id;
	char sec;
	public student(String name, int id, char sec) {
		
		this.name = name;
		this.id = id;
		this.sec = sec;
	}
	@Override
	public String toString() {
		return "student [name=" + name + ", id=" + id + ", sec=" + sec + "]";
	}
	
	
	
	
	

}
